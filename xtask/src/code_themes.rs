//! The code themes the binary carries: every base16 scheme of tinted-theming/schemes at one pinned commit, read into one TOML file.
//!
//! `cargo xtask code-themes fetch` reads the repository's tree, every scheme under `base16/`, and the license, and writes `themes/code/`.
//! `cargo xtask code-themes verify` checks the written file without the network, as `check` does.

use crate::font_catalog::Fetcher;
use crate::fonts::digest;
use crate::fs;
use anyhow::{Context, Result, ensure};
use serde::{Deserialize, Serialize};
use std::path::Path;

/// Where the schemes and their license live.
pub const SCHEMES: &str = "themes/code/schemes.toml";
pub const LICENSE: &str = "themes/code/LICENSE";
/// The repository the schemes come from, and the commit every scheme is read at.
pub const REPOSITORY: &str = "tinted-theming/schemes";
pub const COMMIT: &str = "3ac91137e879502c442ab89ba0f1a98077d0da9d";
/// Where the repository's tree and its raw files are read from.
const API_ORIGIN: &str = "https://api.github.com/repos";
const RAW_ORIGIN: &str = "https://raw.githubusercontent.com";
/// The directory of the base16 schemes and the license file, inside the repository.
const BASE16_DIRECTORY: &str = "base16/";
const LICENSE_FILE: &str = "LICENSE";
/// The extensions a scheme file carries.
const EXTENSIONS: [&str; 2] = [".yaml", ".yml"];
/// The kind of a tree entry that is a file.
const BLOB: &str = "blob";
/// Where fetched files are kept between runs.
const CACHE: &str = "target/schemes-cache";
const TREE_FILE: &str = "tree.json";
/// The system every scheme declares.
const SYSTEM: &str = "base16";
/// The variants a scheme may declare.
pub const VARIANTS: [&str; 2] = ["dark", "light"];
/// The colors of a palette and the length of each as `#rrggbb`.
pub const PALETTE_SIZE: usize = 16;
const COLOR_LENGTH: usize = 7;
const PALETTE_KEY_PREFIX: &str = "base";
const HEX_RADIX: u32 = 16;
/// Two neighbors of the sorted schemes, whose slugs must differ.
const PAIR: usize = 2;
const HEADER: &str = "# Generated by `cargo xtask code-themes fetch` from tinted-theming/schemes at the pinned commit; edit nothing by hand.\n";

/// The schemes file: the commit, the digest of the license beside it, and every scheme by slug.
#[derive(Debug, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub struct Schemes {
    pub commit: String,
    pub license_sha256: String,
    pub scheme: Vec<Scheme>,
}

/// One base16 scheme: its file stem as the slug a theme names, and the sixteen colors of its palette.
#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(deny_unknown_fields)]
pub struct Scheme {
    pub slug: String,
    pub name: String,
    pub author: String,
    pub variant: String,
    pub palette: Vec<String>,
}

#[derive(Debug, Deserialize)]
struct Tree {
    tree: Vec<Entry>,
}

#[derive(Debug, Deserialize)]
struct Entry {
    path: String,
    #[serde(rename = "type")]
    kind: String,
}

/// The scalar after a key: the quoted text, or the text up to a comment.
fn scalar(rest: &str) -> String {
    let rest = rest.trim();
    for quote in ['"', '\''] {
        if let Some(quoted) = rest.strip_prefix(quote) {
            return quoted.split(quote).next().unwrap_or_default().to_owned();
        }
    }
    rest.split(" #").next().unwrap_or(rest).trim().to_owned()
}

/// Whether `text` spells a color as `#rrggbb` in lowercase.
#[must_use]
pub fn is_color(text: &str) -> bool {
    text.len() == COLOR_LENGTH
        && text.starts_with('#')
        && text
            .bytes()
            .skip(1)
            .all(|byte| byte.is_ascii_digit() || (b'a'..=b'f').contains(&byte))
}

/// Whether `text` is a slug: lowercase letters, digits, and dashes.
#[must_use]
pub fn is_slug(text: &str) -> bool {
    !text.is_empty()
        && text
            .bytes()
            .all(|byte| byte.is_ascii_lowercase() || byte.is_ascii_digit() || byte == b'-')
}

/// The scheme in a base16 YAML file, read line by line, since the files hold scalars and one nested map alone.
///
/// # Errors
///
/// Returns an error when the file is not a base16 scheme with a name, a variant, and sixteen colors.
pub fn parse_scheme(slug: &str, text: &str) -> Result<Scheme> {
    let mut system = None;
    let mut name = None;
    let mut author = None;
    let mut variant = None;
    let mut palette: Vec<Option<String>> = vec![None; PALETTE_SIZE];
    for line in text.lines() {
        let trimmed = line.trim_start();
        if trimmed.is_empty() || trimmed.starts_with('#') {
            continue;
        }
        let Some((key, rest)) = trimmed.split_once(':') else {
            continue;
        };
        let value = scalar(rest);
        match key.trim() {
            "system" => system = Some(value),
            "name" => name = Some(value),
            "author" => author = Some(value),
            "variant" => variant = Some(value),
            key => {
                if let Some(digits) = key.strip_prefix(PALETTE_KEY_PREFIX)
                    && let Ok(index) = usize::from_str_radix(digits, HEX_RADIX)
                    && let Some(slot) = palette.get_mut(index)
                {
                    *slot = Some(value.to_ascii_lowercase());
                }
            }
        }
    }
    ensure!(
        system.as_deref() == Some(SYSTEM),
        "{slug} declares the system {system:?}, not {SYSTEM}"
    );
    let name = name.context("no name")?;
    ensure!(!name.is_empty(), "{slug} has an empty name");
    let variant = variant.context("no variant")?;
    ensure!(
        VARIANTS.contains(&variant.as_str()),
        "{slug} declares the variant {variant}, not dark or light"
    );
    let mut colors = Vec::with_capacity(PALETTE_SIZE);
    for (index, color) in palette.into_iter().enumerate() {
        let color = color.with_context(|| format!("{slug} lacks base{index:02X}"))?;
        ensure!(
            is_color(&color),
            "{slug} spells base{index:02X} as {color}, not #rrggbb"
        );
        colors.push(color);
    }
    Ok(Scheme {
        slug: slug.to_owned(),
        name,
        author: author.unwrap_or_default(),
        variant,
        palette: colors,
    })
}

/// The slug of a scheme file under `base16/`, or `None` for any other path.
fn slug_of(path: &str) -> Option<&str> {
    let file = path.strip_prefix(BASE16_DIRECTORY)?;
    EXTENSIONS
        .iter()
        .find_map(|extension| file.strip_suffix(extension))
        .filter(|stem| is_slug(stem))
}

/// Fetches every scheme and the license at the pinned commit and writes `themes/code/`.
///
/// # Errors
///
/// Returns an error when the network fails, a scheme file is not a base16 scheme, or two files share a slug.
pub fn generate(root: &Path) -> Result<()> {
    let fetcher = Fetcher::new(root, CACHE);
    let tree_url = format!("{API_ORIGIN}/{REPOSITORY}/git/trees/{COMMIT}?recursive=1");
    let tree_bytes = fetcher
        .fetch(&tree_url, Path::new(TREE_FILE))?
        .context("the repository has no tree at the pinned commit")?;
    let tree: Tree = serde_json::from_slice(&tree_bytes).context("parse the tree")?;
    let mut schemes = Vec::new();
    let mut failures = Vec::new();
    for entry in tree.tree.iter().filter(|entry| entry.kind == BLOB) {
        let Some(slug) = slug_of(&entry.path) else {
            continue;
        };
        let url = format!("{RAW_ORIGIN}/{REPOSITORY}/{COMMIT}/{}", entry.path);
        let file_name = entry
            .path
            .trim_start_matches(BASE16_DIRECTORY)
            .replace('/', "_");
        match fetcher.fetch(&url, Path::new(&file_name)) {
            Ok(Some(bytes)) => match String::from_utf8(bytes)
                .context("not UTF-8")
                .and_then(|text| parse_scheme(slug, &text))
            {
                Ok(scheme) => schemes.push(scheme),
                Err(error) => failures.push(format!("{}: {error:#}", entry.path)),
            },
            Ok(None) => failures.push(format!("{}: not at the commit", entry.path)),
            Err(error) => failures.push(format!("{}: {error:#}", entry.path)),
        }
    }
    ensure!(
        failures.is_empty(),
        "{} schemes could not be read:\n{}",
        failures.len(),
        failures.join("\n")
    );
    ensure!(!schemes.is_empty(), "the tree holds no base16 scheme");
    schemes.sort_by(|a, b| a.slug.cmp(&b.slug));
    if let Some([first, _]) = schemes
        .windows(PAIR)
        .find(|pair| matches!(pair, [a, b] if a.slug == b.slug))
    {
        anyhow::bail!("two scheme files share the slug `{}`", first.slug);
    }
    let license = fetcher
        .fetch(
            &format!("{RAW_ORIGIN}/{REPOSITORY}/{COMMIT}/{LICENSE_FILE}"),
            Path::new(LICENSE_FILE),
        )?
        .context("the repository has no license at the pinned commit")?;
    fs::write(&root.join(LICENSE), &license)?;
    let document = Schemes {
        commit: String::from(COMMIT),
        license_sha256: digest(&license),
        scheme: schemes,
    };
    let text = toml::to_string_pretty(&document).context("serialize the schemes")?;
    fs::write(&root.join(SCHEMES), format!("{HEADER}{text}").as_bytes())?;
    eprintln!("code-themes: {} schemes written", document.scheme.len());
    Ok(())
}

/// Every way the schemes file disagrees with its own rules, without the network.
///
/// # Errors
///
/// Returns an error when a file cannot be read or parsed.
pub fn findings(root: &Path) -> Result<Vec<String>> {
    let document: Schemes = toml::from_str(&fs::read_to_string(&root.join(SCHEMES))?)
        .with_context(|| format!("parse {SCHEMES}"))?;
    let mut findings = Vec::new();
    if document.commit != COMMIT {
        findings.push(format!(
            "{SCHEMES} pins the commit {}, not {COMMIT}",
            document.commit
        ));
    }
    let license = root.join(LICENSE);
    if fs::is_file(&license)? {
        let actual = digest(&fs::read(&license)?);
        if actual != document.license_sha256 {
            findings.push(format!(
                "{LICENSE} has the digest {actual}, not the pinned {}",
                document.license_sha256
            ));
        }
    } else {
        findings.push(format!("{LICENSE} is missing"));
    }
    for (index, scheme) in document.scheme.iter().enumerate() {
        if !is_slug(&scheme.slug) {
            findings.push(format!("`{}` is not a slug", scheme.slug));
        }
        if let Some(previous) = index.checked_sub(1).and_then(|at| document.scheme.get(at))
            && previous.slug >= scheme.slug
        {
            findings.push(format!(
                "`{}` follows `{}`, out of order or twice",
                scheme.slug, previous.slug
            ));
        }
        if scheme.name.is_empty() {
            findings.push(format!("`{}` has no name", scheme.slug));
        }
        if !VARIANTS.contains(&scheme.variant.as_str()) {
            findings.push(format!(
                "`{}` declares the variant {}, not dark or light",
                scheme.slug, scheme.variant
            ));
        }
        if scheme.palette.len() != PALETTE_SIZE {
            findings.push(format!(
                "`{}` has {} colors, not {PALETTE_SIZE}",
                scheme.slug,
                scheme.palette.len()
            ));
        }
        for color in &scheme.palette {
            if !is_color(color) {
                findings.push(format!(
                    "`{}` spells a color as {color}, not #rrggbb",
                    scheme.slug
                ));
            }
        }
    }
    Ok(findings)
}

/// Refuses a schemes file that breaks its rules, naming each finding.
///
/// # Errors
///
/// Returns an error listing every finding, or when a file cannot be read.
pub fn verify(root: &Path) -> Result<()> {
    let found = findings(root)?;
    ensure!(
        found.is_empty(),
        "the code themes disagree with their rules:\n{}",
        found.join("\n")
    );
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::{COMMIT, LICENSE, SCHEMES, findings, is_color, is_slug, parse_scheme, slug_of};
    use crate::fonts::digest;
    use crate::fs;

    const DRACULA: &str = "system: \"base16\"\nname: \"Dracula\"\nauthor: \"clach04 (https://github.com/clach04)\"\ndescription: \"based on: a spec\"\nvariant: \"dark\"\n# a comment: with a colon\npalette:\n  base00: \"#282a36\"  # Default Background\n  base01: \"#21222c\"\n  base02: \"#44475A\"\n  base03: \"#6272a4\"\n  base04: \"#9ea8c7\"\n  base05: \"#f8f8f2\"\n  base06: \"#f8f8f2\"\n  base07: \"#ffffff\"\n  base08: \"#ff5555\"\n  base09: \"#FFB86C\"\n  base0A: \"#f1fa8c\"\n  base0B: \"#50fa7b\"\n  base0C: \"#8be9fd\"\n  base0D: \"#bd93f9\"\n  base0E: \"#ff79c6\"\n  base0F: \"#993333\"\n";

    #[test]
    fn a_scheme_reads_its_scalars_and_its_palette_in_lowercase() {
        let scheme = parse_scheme("dracula", DRACULA).unwrap();
        assert_eq!(scheme.name, "Dracula");
        assert_eq!(scheme.author, "clach04 (https://github.com/clach04)");
        assert_eq!(scheme.variant, "dark");
        assert_eq!(scheme.palette.len(), 16);
        assert_eq!(scheme.palette[0], "#282a36");
        assert_eq!(scheme.palette[2], "#44475a");
        assert_eq!(scheme.palette[9], "#ffb86c");
        assert_eq!(scheme.palette[15], "#993333");
        let unquoted = parse_scheme("x", &DRACULA.replace("\"#282a36\"", "#282a36")).unwrap();
        assert_eq!(unquoted.palette[0], "#282a36");
        let single = parse_scheme("x", &DRACULA.replace("\"Dracula\"", "'Dracula'")).unwrap();
        assert_eq!(single.name, "Dracula");
        parse_scheme("x", &DRACULA.replace("base0F", "base1F")).unwrap_err();
        parse_scheme("x", &DRACULA.replace("\"dark\"", "\"dim\"")).unwrap_err();
        parse_scheme("x", &DRACULA.replace("\"#993333\"", "\"#99333\"")).unwrap_err();
        parse_scheme("x", &DRACULA.replace("\"base16\"", "\"base24\"")).unwrap_err();
        parse_scheme("x", &DRACULA.replace("name: \"Dracula\"", "name: \"\"")).unwrap_err();
    }

    #[test]
    fn slugs_colors_and_tree_paths_follow_their_grammars() {
        assert!(is_slug("tokyo-night-dark"));
        assert!(is_slug("3024"));
        assert!(!is_slug("Dracula"));
        assert!(!is_slug(""));
        assert!(is_color("#ffb86c"));
        assert!(!is_color("#FFB86C"));
        assert!(!is_color("ffb86c0"));
        assert!(!is_color("#ffb86"));
        assert_eq!(slug_of("base16/dracula.yaml"), Some("dracula"));
        assert_eq!(slug_of("base16/cyberpunk.yml"), Some("cyberpunk"));
        assert_eq!(slug_of("base24/dracula.yaml"), None);
        assert_eq!(slug_of("base16/README.md"), None);
    }

    #[test]
    fn the_carried_schemes_pass_their_own_rules_and_each_breach_is_named() {
        let root = tempfile::tempdir().unwrap();
        fs::write(&root.path().join(LICENSE), b"MIT").unwrap();
        let sound = format!(
            "commit = \"{COMMIT}\"\nlicense_sha256 = \"{}\"\n\n[[scheme]]\nslug = \"a\"\nname = \"A\"\nauthor = \"\"\nvariant = \"dark\"\npalette = [{}]\n",
            digest(b"MIT"),
            vec!["\"#000000\""; 16].join(", ")
        );
        fs::write(&root.path().join(SCHEMES), sound.as_bytes()).unwrap();
        assert_eq!(findings(root.path()).unwrap(), Vec::<String>::new());
        let broken = sound
            .replace("slug = \"a\"", "slug = \"A\"")
            .replace("variant = \"dark\"", "variant = \"dim\"")
            .replace("\"#000000\", \"#000000\"]", "\"#000000\", \"#00000\"]")
            .replace(COMMIT, "0");
        fs::write(&root.path().join(SCHEMES), broken.as_bytes()).unwrap();
        fs::write(&root.path().join(LICENSE), b"changed").unwrap();
        let found = findings(root.path()).unwrap().join("\n");
        for expected in [
            "is not a slug",
            "not dark or light",
            "not #rrggbb",
            "pins the commit 0",
            "has the digest",
        ] {
            assert!(found.contains(expected), "{expected}: {found}");
        }
        let doubled = format!(
            "{sound}\n[[scheme]]\nslug = \"a\"\nname = \"A\"\nauthor = \"\"\nvariant = \"light\"\npalette = [{}]\n",
            vec!["\"#ffffff\""; 16].join(", ")
        );
        fs::write(&root.path().join(SCHEMES), doubled.as_bytes()).unwrap();
        fs::write(&root.path().join(LICENSE), b"MIT").unwrap();
        assert!(
            findings(root.path())
                .unwrap()
                .join("\n")
                .contains("out of order or twice")
        );
    }
}
