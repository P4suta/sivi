//! The SMT lemmas about millipoint rounding, generated from the core's constants and decided by Z3.
//!
//! The fixed-point verdict of `fit_rules` and the real-valued verdict a reader has in mind agree outside a band of one millipoint around the tolerance.
//! Z3 decides the lemmas over reals and integers, which no Rust verifier models directly.

use crate::tool::{Tool, capture};
use crate::{fs, portable};
use anyhow::{Context, Result, bail, ensure};
use std::path::Path;
use syn::visit::Visit;

/// The source the constants come from.
pub const SOURCE: &str = "crates/sivi-core/src/length.rs";

/// The lemmas every check must find unsatisfiable when negated.
pub const LEMMAS: &str = "specs/smt/millipoints.smt2";

/// A claim that is false by one millipoint of rounding, which Z3 must find satisfiable to show the gate can fail.
pub const NEGATIVE: &str = "specs/smt/millipoints-negative.smt2";

/// The pinned solver version the gate requires.
pub const Z3_VERSION: &str = "5.1.0";

const TIMEOUT_SECONDS: &str = "30";
const EXPECTED_LEMMAS: &str = "unsat\nunsat\n";
const EXPECTED_NEGATIVE: &str = "sat\n";

/// The constants of the core that the lemmas quantify over.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct Constants {
    pub millipoints_per_point: i64,
    pub epsilon_millipoints: i64,
}

#[derive(Default)]
struct ConstantVisitor<'ast> {
    millipoints_per_point: Option<&'ast syn::Expr>,
    epsilon_millipoints: Option<&'ast syn::Expr>,
}

/// The integer an initializer names, directly or as the one argument of a constructor call.
fn integer(expression: &syn::Expr) -> Result<Option<i64>> {
    if let syn::Expr::Lit(syn::ExprLit {
        lit: syn::Lit::Int(literal),
        ..
    }) = expression
    {
        let value = literal
            .base10_parse::<i64>()
            .context("an integer constant fits an i64")?;
        return Ok(Some(value));
    }
    if let syn::Expr::Call(call) = expression {
        return call.args.first().map_or(Ok(None), integer);
    }
    Ok(None)
}

impl<'ast> Visit<'ast> for ConstantVisitor<'ast> {
    fn visit_item_const(&mut self, item: &'ast syn::ItemConst) {
        if item.ident == "MILLIPOINTS_PER_POINT" {
            self.millipoints_per_point = Some(&item.expr);
        }
        if item.ident == "EPSILON" {
            self.epsilon_millipoints = Some(&item.expr);
        }
        syn::visit::visit_item_const(self, item);
    }
}

/// The constants `source` defines.
///
/// # Errors
///
/// Returns an error when the source fails to parse or lacks a constant.
pub fn constants(source: &str) -> Result<Constants> {
    let file = syn::parse_file(source).context("parse the length module")?;
    let mut visitor = ConstantVisitor::default();
    visitor.visit_file(&file);
    let millipoints_per_point = visitor
        .millipoints_per_point
        .context("the length module defines MILLIPOINTS_PER_POINT")?;
    let epsilon_millipoints = visitor
        .epsilon_millipoints
        .context("the length module defines EPSILON")?;
    Ok(Constants {
        millipoints_per_point: integer(millipoints_per_point)?
            .context("MILLIPOINTS_PER_POINT is an integer")?,
        epsilon_millipoints: integer(epsilon_millipoints)?
            .context("EPSILON is built from an integer")?,
    })
}

fn preamble(constants: Constants) -> String {
    format!(
        "; Generated by `cargo xtask gen` from {SOURCE}; edit the constants there, never this file.\n\
         ; h and a are the true heights in points; H and A are their roundings to millipoints.\n\
         (set-logic ALL)\n\
         (declare-const h Real)\n\
         (declare-const a Real)\n\
         (declare-const H Int)\n\
         (declare-const A Int)\n\
         (define-fun scale () Real {}.0)\n\
         (define-fun epsilon () Int {})\n\
         ; Rounding to the nearest millipoint moves a value by at most half a millipoint.\n\
         (assert (<= (- (* scale h) (to_real H)) 0.5))\n\
         (assert (<= (- (to_real H) (* scale h)) 0.5))\n\
         (assert (<= (- (* scale a) (to_real A)) 0.5))\n\
         (assert (<= (- (to_real A) (* scale a)) 0.5))\n",
        constants.millipoints_per_point, constants.epsilon_millipoints
    )
}

/// The lemma file for `constants`.
#[must_use]
pub fn lemmas(constants: Constants) -> String {
    format!(
        "{}\
         ; Lemma 1: an overflow verdict means the true excess passes epsilon minus one millipoint.\n\
         (push)\n\
         (assert (> (- H A) epsilon))\n\
         (assert (<= (* scale (- h a)) (to_real (- epsilon 1))))\n\
         (check-sat)\n\
         (pop)\n\
         ; Lemma 2: a fit verdict means the true excess stays within epsilon plus one millipoint.\n\
         (push)\n\
         (assert (<= (- H A) epsilon))\n\
         (assert (> (* scale (- h a)) (to_real (+ epsilon 1))))\n\
         (check-sat)\n\
         (pop)\n",
        preamble(constants)
    )
}

/// The negative control for `constants`: exact agreement, which rounding breaks.
#[must_use]
pub fn negative(constants: Constants) -> String {
    format!(
        "{}\
         ; A false claim: the fixed-point verdict never overflows where the true excess is within epsilon.\n\
         (assert (> (- H A) epsilon))\n\
         (assert (<= (* scale (- h a)) (to_real epsilon)))\n\
         (check-sat)\n",
        preamble(constants)
    )
}

fn current(root: &Path) -> Result<Constants> {
    constants(&fs::read_to_string(&root.join(SOURCE))?)
}

/// Writes both SMT files from the core's constants.
///
/// # Errors
///
/// Returns an error when the constants cannot be read or a file cannot be written.
pub fn generate(root: &Path) -> Result<()> {
    let constants = current(root)?;
    fs::write(&root.join(LEMMAS), lemmas(constants).as_bytes())?;
    fs::write(&root.join(NEGATIVE), negative(constants).as_bytes())
}

/// Refuses SMT files that differ from what the core's constants generate.
///
/// # Errors
///
/// Returns an error naming the stale file.
pub fn check(root: &Path) -> Result<()> {
    let constants = current(root)?;
    for (path, expected) in [(LEMMAS, lemmas(constants)), (NEGATIVE, negative(constants))] {
        let full = root.join(path);
        ensure!(
            fs::is_file(&full)?,
            "{path} is missing; run `cargo xtask gen`"
        );
        ensure!(
            fs::read_to_string(&full)? == expected,
            "{path} is stale; run `cargo xtask gen`"
        );
    }
    Ok(())
}

fn solve(root: &Path, path: &str) -> Result<String> {
    capture(
        Tool::Z3
            .command(root)
            .args([
                "-smt2",
                &format!("-T:{TIMEOUT_SECONDS}"),
                "smt.random_seed=0",
                "sat.random_seed=0",
            ])
            .arg(root.join(path)),
        "z3",
    )
}

/// Decides the lemmas with the pinned Z3 and requires the negative control to be satisfiable.
///
/// # Errors
///
/// Returns an error when the solver is missing, a lemma is not refuted, or the false claim is not found satisfiable.
pub fn verify(root: &Path) -> Result<()> {
    let version = capture(Tool::Z3.command(root).arg("--version"), "z3")?;
    ensure!(
        version.contains(Z3_VERSION),
        "the pinned z3 {Z3_VERSION} is unavailable; found: {}",
        version.trim()
    );
    check(root)?;
    let outcome = solve(root, LEMMAS)?;
    ensure!(
        outcome == EXPECTED_LEMMAS,
        "z3 answered {outcome:?} over {} instead of {EXPECTED_LEMMAS:?}; a timeout answers `timeout` and never counts as a proof",
        portable(Path::new(LEMMAS))
    );
    let control = solve(root, NEGATIVE)?;
    if control != EXPECTED_NEGATIVE {
        bail!(
            "z3 answered {control:?} over {} instead of {EXPECTED_NEGATIVE:?}; the gate cannot show it fails",
            portable(Path::new(NEGATIVE))
        );
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::{Constants, constants, lemmas, negative};

    const LENGTH_SOURCE: &str = "pub const MILLIPOINTS_PER_POINT: i64 = 1000;\npub const EPSILON: Length = Length::from_millipoints(10);\n";

    #[test]
    fn the_constants_are_read_from_the_length_module() {
        assert_eq!(
            constants(LENGTH_SOURCE).unwrap(),
            Constants {
                millipoints_per_point: 1000,
                epsilon_millipoints: 10
            }
        );
        constants("pub const OTHER: i64 = 1;").unwrap_err();
        constants("fn broken(").unwrap_err();
    }

    #[test]
    fn the_generated_files_name_the_constants_and_their_checks() {
        let constants = Constants {
            millipoints_per_point: 1000,
            epsilon_millipoints: 10,
        };
        let text = lemmas(constants);
        assert!(text.contains("(define-fun scale () Real 1000.0)"));
        assert!(text.contains("(define-fun epsilon () Int 10)"));
        assert_eq!(text.matches("(check-sat)").count(), 2);
        let control = negative(constants);
        assert_eq!(control.matches("(check-sat)").count(), 1);
        assert!(control.contains("A false claim"));
    }
}
