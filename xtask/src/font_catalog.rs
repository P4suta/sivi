//! The font catalog generator, which fetches every family `fonts/families.toml` lists from google/fonts at its pinned commit and pins each file by its digest.

use crate::fonts::digest;
use crate::fs;
use anyhow::{Context, Result, anyhow, bail, ensure};
use serde::Deserialize;
use sivi_theme::catalog::{Catalog, Category, Family, FontEntry, RAW_ORIGIN, encoded};
use sivi_theme::faces;
use std::path::{Path, PathBuf};
use std::time::Duration;

/// The curated list the generator reads.
pub const FAMILIES: &str = "fonts/families.toml";
/// The catalog the generator writes and the binary carries.
pub const CATALOG: &str = "fonts/catalog.toml";
/// Where Google Fonts publishes the metadata of every family.
const METADATA_URL: &str = "https://fonts.google.com/metadata/fonts";
/// The guard Google Fonts prefixes to the metadata document.
const METADATA_GUARD: &str = ")]}'";
/// The file of a family that names its files and its license.
const METADATA_FILE: &str = "METADATA.pb";
/// Where fetched files are kept between runs.
const CACHE: &str = "target/fonts-cache";
/// The license directories of google/fonts, each with its license identifier and its license file.
const LICENSE_DIRECTORIES: [(&str, &str, &str); 3] = [
    ("ofl", "OFL-1.1", "OFL.txt"),
    ("apache", "Apache-2.0", "LICENSE.txt"),
    ("ufl", "UFL-1.0", "UFL.txt"),
];
/// The subset Google Fonts lists for its own menus, which names no writing system.
const MENU_SUBSET: &str = "menu";
const TIMEOUT: Duration = Duration::from_secs(600);
/// The most bytes one fetched file may hold.
const FILE_LIMIT: u64 = 64 * 1024 * 1024;
const USER_AGENT: &str = "sivi-xtask";
const NOT_FOUND: u16 = 404;

const HEADER: &str = "# Generated by `cargo xtask fonts catalog` from google/fonts at the pinned commit; edit `fonts/families.toml` instead.\n";

/// The curated list of families.
#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Families {
    pub commit: String,
    pub family: Vec<Listed>,
}

/// One listed family, with its directory when the naming rule does not find it and the family its files carry when that differs.
#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Listed {
    /// The name Google Fonts lists the family under.
    pub name: String,
    pub path: Option<String>,
    /// The family name the files carry, which the themes use, when it differs from the listing.
    pub family: Option<String>,
}

impl Listed {
    /// The family name the files carry, which the themes use.
    #[must_use]
    pub fn carried(&self) -> &str {
        self.family.as_deref().unwrap_or(&self.name)
    }
}

#[derive(Debug, Deserialize)]
struct Metadata {
    #[serde(rename = "familyMetadataList")]
    families: Vec<MetadataFamily>,
}

#[derive(Debug, Deserialize)]
struct MetadataFamily {
    family: String,
    category: String,
    subsets: Vec<String>,
}

/// What `METADATA.pb` says about a family.
#[derive(Debug, Default, PartialEq, Eq)]
pub struct MetadataFields {
    pub name: String,
    pub filenames: Vec<String>,
}

/// The directory name google/fonts gives a family: its name lowercased without spaces.
#[must_use]
pub fn directory(name: &str) -> String {
    name.chars()
        .filter(|character| !character.is_whitespace())
        .flat_map(char::to_lowercase)
        .collect()
}

/// The catalog category of a Google Fonts category.
#[must_use]
pub fn category(text: &str) -> Option<Category> {
    match text {
        "Sans Serif" => Some(Category::Sans),
        "Serif" => Some(Category::Serif),
        "Display" => Some(Category::Display),
        "Handwriting" => Some(Category::Handwriting),
        "Monospace" => Some(Category::Mono),
        _ => None,
    }
}

/// The quoted value `line` gives `key`, as the text form of `METADATA.pb` spells it.
fn field<'a>(line: &'a str, key: &str) -> Option<&'a str> {
    line.trim()
        .strip_prefix(key)?
        .strip_prefix(": \"")?
        .strip_suffix('"')
}

/// The family name and the font files `METADATA.pb` names.
#[must_use]
pub fn metadata_fields(text: &str) -> MetadataFields {
    let mut fields = MetadataFields::default();
    for line in text.lines() {
        if fields.name.is_empty()
            && let Some(name) = field(line, "name")
        {
            fields.name = String::from(name);
        }
        if let Some(filename) = field(line, "filename") {
            fields.filenames.push(String::from(filename));
        }
    }
    fields
}

mod raw {
    #![expect(
        clippy::disallowed_methods,
        reason = "the catalog generator is the tasks' one network owner, and builds its agent here"
    )]

    /// An agent with the generator's timeout and name.
    pub(super) fn agent() -> ureq::Agent {
        ureq::Agent::config_builder()
            .timeout_global(Some(super::TIMEOUT))
            .user_agent(super::USER_AGENT)
            .build()
            .into()
    }
}

/// The tasks' one way to the network: an agent with a cache directory under the checkout.
pub(crate) struct Fetcher {
    agent: ureq::Agent,
    cache: PathBuf,
}

impl Fetcher {
    pub(crate) fn new(root: &Path, cache: &str) -> Self {
        Self {
            agent: raw::agent(),
            cache: root.join(cache),
        }
    }

    /// The bytes at `url`, from the cache under `name` when present, or `None` when the server has no such file.
    pub(crate) fn fetch(&self, url: &str, name: &Path) -> Result<Option<Vec<u8>>> {
        let cached = self.cache.join(name);
        if fs::is_file(&cached)? {
            return Ok(Some(fs::read(&cached)?));
        }
        let mut response = match self.agent.get(url).call() {
            Ok(response) => response,
            Err(ureq::Error::StatusCode(NOT_FOUND)) => return Ok(None),
            Err(error) => return Err(error).with_context(|| format!("fetch {url}")),
        };
        let bytes = response
            .body_mut()
            .with_config()
            .limit(FILE_LIMIT)
            .read_to_vec()
            .with_context(|| format!("read {url}"))?;
        fs::write(&cached, &bytes)?;
        Ok(Some(bytes))
    }
}

fn metadata(fetcher: &Fetcher) -> Result<Metadata> {
    let bytes = fetcher
        .fetch(METADATA_URL, Path::new("metadata.json"))?
        .context("Google Fonts publishes no metadata")?;
    let text = String::from_utf8(bytes).context("the metadata is not UTF-8")?;
    let json = text.strip_prefix(METADATA_GUARD).unwrap_or(&text);
    serde_json::from_str(json).context("parse the metadata")
}

/// The directory, license, license file, and metadata fields of `listed`, probing each license directory in turn.
fn locate(
    fetcher: &Fetcher,
    commit: &str,
    listed: &Listed,
) -> Result<(String, &'static str, &'static str, MetadataFields)> {
    let derived = directory(&listed.name);
    let candidates: Vec<(String, &str, &str)> = match &listed.path {
        Some(path) => {
            let (_, license, file) = LICENSE_DIRECTORIES
                .iter()
                .find(|(prefix, _, _)| path.starts_with(&format!("{prefix}/")))
                .with_context(|| format!("`{path}` starts with none of the license directories"))?;
            vec![(path.clone(), *license, *file)]
        }
        None => LICENSE_DIRECTORIES
            .iter()
            .map(|(prefix, license, file)| (format!("{prefix}/{derived}"), *license, *file))
            .collect(),
    };
    for (path, license, file) in candidates {
        let url = format!("{RAW_ORIGIN}/{commit}/{path}/{METADATA_FILE}");
        if let Some(bytes) = fetcher.fetch(&url, &Path::new(&path).join(METADATA_FILE))? {
            let text = String::from_utf8(bytes)
                .with_context(|| format!("{path}/{METADATA_FILE} is not UTF-8"))?;
            return Ok((path, license, file, metadata_fields(&text)));
        }
    }
    bail!(
        "`{}` is under none of the license directories as `{derived}`; set `path` in {FAMILIES}",
        listed.name
    )
}

/// The catalog entry of one font file, read from its bytes.
///
/// # Errors
///
/// Returns an error when the bytes are not a font.
pub fn entry(name: &str, bytes: &[u8]) -> Result<(String, FontEntry)> {
    let face = faces::face(bytes).map_err(|error| anyhow!("{name} is not a font: {error:?}"))?;
    let entry = FontEntry {
        name: String::from(name),
        sha256: digest(bytes),
        bytes: u64::try_from(bytes.len())?,
        italic: face.italic,
        weights: [face.weights.lowest.value(), face.weights.highest.value()],
    };
    Ok((String::from(face.family.as_str()), entry))
}

/// What one family came to: its catalog entry and the files set aside because Typst lists them under another name.
struct Cataloged {
    family: Family,
    set_aside: Vec<String>,
}

fn family(
    fetcher: &Fetcher,
    commit: &str,
    metadata: &Metadata,
    listed: &Listed,
) -> Result<Cataloged> {
    let known = metadata
        .families
        .iter()
        .find(|known| known.family == listed.name)
        .with_context(|| format!("Google Fonts lists no family named `{}`", listed.name))?;
    let category = category(&known.category).with_context(|| {
        format!(
            "`{}` has the category `{}`, which the catalog does not know",
            listed.name, known.category
        )
    })?;
    let (path, license, license_file, fields) = locate(fetcher, commit, listed)?;
    ensure!(
        fields.name == listed.name,
        "`{}` is named `{}` in its {METADATA_FILE}",
        listed.name,
        fields.name
    );
    let mut files = Vec::new();
    let mut set_aside = Vec::new();
    for filename in &fields.filenames {
        let url = format!("{RAW_ORIGIN}/{commit}/{path}/{}", encoded(filename));
        let bytes = fetcher
            .fetch(&url, &Path::new(&path).join(filename))?
            .with_context(|| format!("{path}/{filename} is missing at the commit"))?;
        let (carried, found) = entry(filename, &bytes)?;
        if carried == listed.carried() {
            files.push(found);
        } else {
            set_aside.push(format!(
                "{}: {filename} is listed under `{carried}`, not `{}`",
                listed.name,
                listed.carried()
            ));
        }
    }
    ensure!(
        !files.is_empty(),
        "`{}` has no file under the name `{}`; set `family` in {FAMILIES} to the name its files carry",
        listed.name,
        listed.carried()
    );
    let license_url = format!("{RAW_ORIGIN}/{commit}/{path}/{license_file}");
    let license_bytes = fetcher.fetch(&license_url, &Path::new(&path).join(license_file))?;
    let mut scripts = known.subsets.clone();
    scripts.retain(|subset| subset != MENU_SUBSET);
    scripts.sort();
    let listed_name = (listed.carried() != listed.name).then(|| listed.name.clone());
    Ok(Cataloged {
        family: Family {
            name: String::from(listed.carried()),
            listed: listed_name,
            path,
            category,
            scripts,
            license: String::from(license),
            license_file: license_bytes.as_ref().map(|_| String::from(license_file)),
            license_sha256: license_bytes.as_deref().map(digest),
            file: files,
        },
        set_aside,
    })
}

/// Fetches every listed family and writes the catalog.
///
/// # Errors
///
/// Returns an error when a family is not where the list says, a file is not a font, or the network fails.
pub fn generate(root: &Path) -> Result<()> {
    let families: Families = toml::from_str(&fs::read_to_string(&root.join(FAMILIES))?)
        .with_context(|| format!("parse {FAMILIES}"))?;
    let fetcher = Fetcher::new(root, CACHE);
    let metadata = metadata(&fetcher)?;
    let mut catalog = Catalog {
        commit: families.commit.clone(),
        family: Vec::new(),
    };
    let mut failures = Vec::new();
    for listed in &families.family {
        eprintln!("fonts: {}", listed.name);
        match family(&fetcher, &families.commit, &metadata, listed) {
            Ok(found) => {
                for note in &found.set_aside {
                    eprintln!("fonts: {note}");
                }
                catalog.family.push(found.family);
            }
            Err(error) => failures.push(format!("{}: {error:#}", listed.name)),
        }
    }
    ensure!(
        failures.is_empty(),
        "{} families could not be cataloged:\n{}",
        failures.len(),
        failures.join("\n")
    );
    catalog.family.sort_by(|a, b| a.name.cmp(&b.name));
    let text = toml::to_string_pretty(&catalog).context("serialize the catalog")?;
    fs::write(&root.join(CATALOG), format!("{HEADER}{text}").as_bytes())?;
    Ok(())
}

/// Every way the catalog disagrees with the curated list, without the network.
///
/// # Errors
///
/// Returns an error when either file cannot be read.
pub fn findings(root: &Path) -> Result<Vec<String>> {
    let families: Families = toml::from_str(&fs::read_to_string(&root.join(FAMILIES))?)
        .with_context(|| format!("parse {FAMILIES}"))?;
    let catalog: Catalog = toml::from_str(&fs::read_to_string(&root.join(CATALOG))?)
        .with_context(|| format!("parse {CATALOG}"))?;
    let mut findings = Vec::new();
    if families.commit != catalog.commit {
        findings.push(format!(
            "{CATALOG} pins the commit {}, not the {} of {FAMILIES}",
            catalog.commit, families.commit
        ));
    }
    for listed in &families.family {
        if catalog.family(listed.carried()).is_none() {
            findings.push(format!(
                "{CATALOG} lacks `{}`; run `cargo xtask fonts catalog`",
                listed.carried()
            ));
        }
    }
    for family in &catalog.family {
        if !families
            .family
            .iter()
            .any(|listed| listed.carried() == family.name)
        {
            findings.push(format!(
                "{CATALOG} carries `{}`, which {FAMILIES} does not list",
                family.name
            ));
        }
    }
    Ok(findings)
}

#[cfg(test)]
mod tests {
    use super::{category, directory, encoded, entry, metadata_fields};
    use sivi_theme::catalog::Category;

    const GOTHIC: &[u8] = include_bytes!("../../fonts/BIZUDPGothic-Bold.ttf");
    const DISPLAY: &[u8] = include_bytes!("../../fonts/PlayfairDisplay-Italic[wght].ttf");

    #[test]
    fn the_directory_rule_lowercases_and_drops_spaces() {
        assert_eq!(directory("Noto Sans JP"), "notosansjp");
        assert_eq!(directory("M PLUS 1p"), "mplus1p");
        assert_eq!(encoded("Inter[opsz,wght].ttf"), "Inter%5Bopsz,wght%5D.ttf");
        assert_eq!(category("Sans Serif"), Some(Category::Sans));
        assert_eq!(category("Monospace"), Some(Category::Mono));
        assert_eq!(category("Other"), None);
    }

    #[test]
    fn the_metadata_fields_take_the_first_name_and_every_filename() {
        let text = "name: \"Noto Sans JP\"\nlicense: \"OFL\"\nfonts {\n  name: \"Noto Sans JP\"\n  filename: \"NotoSansJP[wght].ttf\"\n}\nfonts {\n  filename: \"Other.ttf\"\n}\n";
        let fields = metadata_fields(text);
        assert_eq!(fields.name, "Noto Sans JP");
        assert_eq!(fields.filenames, vec!["NotoSansJP[wght].ttf", "Other.ttf"]);
        assert_eq!(metadata_fields("").name, "");
    }

    #[test]
    fn an_entry_reads_a_static_weight_and_a_variable_range() {
        let (family, bold) = entry("BIZUDPGothic-Bold.ttf", GOTHIC).unwrap();
        assert_eq!(family, "BIZ UDPGothic");
        assert_eq!(bold.weights, [700, 700]);
        assert!(!bold.italic);
        assert_eq!(bold.sha256.len(), 64);
        let (display_family, italic) = entry("PlayfairDisplay-Italic[wght].ttf", DISPLAY).unwrap();
        assert_eq!(display_family, "Playfair Display");
        assert_eq!(italic.weights, [400, 900]);
        assert!(italic.italic);
        entry("x.ttf", b"not a font").unwrap_err();
    }
}
